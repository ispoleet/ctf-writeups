def flag_grid_to_buf(flag_grid):
    """Converts a 20x20 grid into a `flag_buf`."""
    flag_buf = []
    q = 0
    for i in range(400):
        if i > 0 and i % 64 == 0:
            flag_buf.append(q)
            q = 0

        q |= flag_grid[i] << (i % 64)

    flag_buf.append(q) # for leftovers

    return flag_buf


